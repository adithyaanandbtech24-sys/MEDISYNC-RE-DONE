                    testName: lab.testName,
                    latestValue: lab.value,
                    unit: lab.unit,
                    status: lab.status,
                    normalRange: lab.normalRange,
                    color: Color.medicalPurpleLight
                )
            }
            .sheet(item: $selectedReport) { report in
                ReportDetailView(report: report)
            }
        }
    }
