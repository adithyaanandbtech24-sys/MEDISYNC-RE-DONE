                            }
                        }
                    }
                    
                    // Reports Section
                    if !filteredReports.isEmpty {
                        Section(header: Text("Medical Reports")) {
                            ForEach(filteredReports) { report in
                                Button(action: { selectedReport = report }) {
                                    VStack(alignment: .leading) {
                                        Text(report.title).font(.headline)
