// MARK: - Organ Timeline Card (Legacy - Graph Based)
struct OrganTimelineCard: View {
    let organName: String
    let icon: String
    let iconColor: Color
    let status: String
    let statusColor: Color
    let graphType: GraphType
    let labResults: [LabResultModel]
    
    @State private var selectedPeriod: TimePeriod = .month
    @State private var showDetailPopup = false
    
    enum GraphType {
        case wave, lineWithDots, area, bar
    }
    
    enum TimePeriod: String, CaseIterable {
        case day = "Day"
        case week = "Week"
        case month = "Month"
        case year = "Year"
    }
    
    // Extract data points for the graph
    // Dynamic Time Period Logic
    var availablePeriods: Set<TimePeriod> {
        let sorted = labResults.sorted { $0.testDate < $1.testDate }
        guard let first = sorted.first?.testDate, let last = sorted.last?.testDate else {
            return [.day]
        }
        
        let span = last.timeIntervalSince(first)
        let dayInSeconds: TimeInterval = 86400
        let yearInSeconds: TimeInterval = 31536000
        
        if span <= dayInSeconds {
             return [.day]
        } else if span > yearInSeconds {
            return [.year]
        } else {
            // "If it is months back then activate months section and disable the other 2"
            return [.month]
        }
    }
    
    var currentPeriodData: [LabResultModel] {
        // Filter logic could go here if we were showing subsets,
        // but for this requirement we are mostly changing the VIEW scale (X-Axis).
        // We pass all data to the chart and let the chart axis handle the visual grouping?
        // Or we filter? The requirement implies the BUTTONS are disabled.
        // For simplicity and chart accuracy, we pass all relevant data.
        return labResults.sorted { $0.testDate < $1.testDate }
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 15) {
            // Header
            HStack {
                Image(systemName: icon)
                    .font(.system(size: 20))
                    .foregroundColor(iconColor)
                
                Text(organName)
                    .font(.system(size: 18, weight: .bold))
                
                Spacer()
                
                HStack(spacing: 5) {
                    Image(systemName: "arrow.up.right")
                        .font(.system(size: 12))
                        .foregroundColor(statusColor)
                    Text(status)
                        .font(.system(size: 14, weight: .medium))
                        .foregroundColor(statusColor)
                }
            }
            
            // Time Period Toggle
            TimePeriodToggle(selectedPeriod: $selectedPeriod, availablePeriods: availablePeriods)
                .onChange(of: availablePeriods) { _, newPeriods in
                    // Auto-select the only available period if current selection is invalid
                    if !newPeriods.contains(selectedPeriod), let first = newPeriods.first {
                        selectedPeriod = first
                    }
                }
                .onAppear {
                    // Initial check
                    if !availablePeriods.contains(selectedPeriod), let first = availablePeriods.first {
                        selectedPeriod = first
                    }
                }
            
            // Graph
            ZStack {
                if labResults.isEmpty {
                    Text("No data available")
                        .font(.caption)
                        .foregroundColor(.gray)
                        .frame(height: 180)
                } else {
                    OrganHealthChart(
                        data: currentPeriodData,
                        graphType: graphType,
                        color: iconColor,
                        timePeriod: selectedPeriod
                    )
                }
            }
            .frame(height: 200) // Slightly taller for axis labels
            
            // Timeline Labels (Simplified)
            HStack {
                Text("Past")
                    .font(.caption)
                    .foregroundColor(.gray)
                Spacer()
                Text("Present")
                    .font(.caption)
                    .foregroundColor(.gray)
            }
        }
        .padding(20)
        .background(Color.white)
        .cornerRadius(20)
        .shadow(color: .black.opacity(0.05), radius: 10, x: 0, y: 5)
        .padding(.horizontal)
        .onTapGesture {
            showDetailPopup = true
        }
        .sheet(isPresented: $showDetailPopup) {
            OrganDetailPopup(
                organName: organName,
                icon: icon,
                iconColor: iconColor,
                graphType: graphType,
                labResults: labResults
            )
        }
        .onAppear {
            if let bestPeriod = availablePeriods.first {
                selectedPeriod = bestPeriod
            }
        }
    }
}

